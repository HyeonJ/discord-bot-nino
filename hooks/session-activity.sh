#!/usr/bin/env bash
# session-activity.sh — PostToolUse 훅. 세션이 도구를 부를 때마다 그 시각을 남긴다.
#
# 🔴 왜 필요한가 (2026-07-29 룬드 실오탐):
#   워치독은 `session-heartbeat-utc`(Stop 훅 = **턴 종료** 시각) 하나로 "말을 하고 있나"를 쟀다.
#   그런데 한 턴이 임계(60분)를 넘으면 그동안 하트비트가 안 찍힌다
#     ⇒ **가장 활발히 일할 때가 가장 죽어 보인다.**
#   룬드 실발동: 63분짜리 턴(X 실험) 도중 "산출 정지 · 수신 38건" 이 Tim 께 나갔다.
#   수신 축(#67)은 이걸 못 막는다 — 웹훅 등이 계속 들어와 게이트를 통과하고,
#   본문에 "38건 들어왔는데 하나도 못 받았어" 라고 **확신까지 실어준다**(니노 외 38건/시간 실측).
#
# 🔑 그래서 축을 하나 더 둔다. **파일을 나누는 게 핵심이다:**
#   session-heartbeat-utc  턴 종료   ← 재시작 따라잡기 **앵커**. 의미를 바꾸면 catchup 이 깨진다
#   session-activity-utc   도구 호출 ← 이 파일. "죽었나" 판정 전용
#   같은 파일에 쓰면 앵커가 오염된다(#63 에서 cron 발화가 앵커를 끌어당기던 것과 같은 형태).
#
# 🔴 계약 — 워치독은 이 파일을 **억제기로만** 쓴다:
#   활동이 신선하면 알림을 **막을 수만** 있고, 활동이 멈췄다고 **혼자서 알림을 내지 않는다**.
#   단조롭기 때문이다 — 억제 전용이면 이 축이 *새 오탐*을 만들 수 없다. 트리거로도 쓰면
#   훅이 죽은 순간이 곧 알림이 되어, 감시를 고치려다 감시가 새 오탐원이 된다.
#   ⇒ 파일 부재는 **정지가 아니라 판정 불가**다. 부재를 정지로 읽으면 훅 하나 빠뜨렸을 때
#     2분마다 사람을 부른다(#64 에서 룬드 상주 루프 코드를 그대로 베꼈으면 날 뻔한 사고).
#
# ⚠️ 알고 넣는 사각: **도구를 한 번도 안 부르는 긴 턴**(순수 생성)은 이 축도 못 덮는다.
#   완전히 덮으려면 턴 시작 신호(UserPromptSubmit)까지 필요하다. 1차는 도구 호출로 간다 —
#   대부분의 긴 턴은 도구를 부르기 때문. **남는 케이스를 알고 넣는 것**이 이 주석의 목적이다.
#
# 계약:
#   · 절대 실패하지 않는다(exit 0 고정). 훅이 죽으면 도구 호출이 방해받는다.
#   · **도구 호출마다** 도는 훅이라 가벼워야 한다 — date 1회 + mv 1회.
#   · 형식은 하트비트와 같은 `...Z`. 워치독이 같은 파서로 읽는다.
set -uo pipefail

BOT_DIR="${ACTIVITY_BOT_DIR:-/home/bpx27/discord-bot-nino}"
OUT="$BOT_DIR/logs/session-activity-utc"

mkdir -p "$BOT_DIR/logs" 2>/dev/null || exit 0

# 원자적 교체 — 워치독이 half-written 파일을 읽는 창을 없앤다.
# $$ 는 훅 프로세스마다 다르므로 동시 호출끼리도 안 부딪힌다.
TMP="$OUT.$$"
if date -u +%Y-%m-%dT%H:%M:%S.000Z > "$TMP" 2>/dev/null; then
    mv -f "$TMP" "$OUT" 2>/dev/null || rm -f "$TMP" 2>/dev/null
else
    rm -f "$TMP" 2>/dev/null
fi

exit 0
