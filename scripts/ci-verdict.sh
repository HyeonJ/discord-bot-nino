#!/usr/bin/env bash
# ci-verdict.sh — 러너의 **세 상태**를 CI 의 **두 상태**로 옮긴다 (정책은 여기 한 곳에만)
#
# 왜 필요한가 (2026-07-28):
#   `scripts/run-tests.sh` 는 0(통과)·1(실패)·2(판정 불가)를 낸다. 그런데 GitHub Actions 의
#   스텝은 **초록/빨강 둘**뿐이다. 이 변환을 워크플로 YAML 안에 인라인으로 쓰면
#     ① 시험할 수 없고 ② 두 레포에서 각자 달라지고 ③ 조용히 틀려도 아무도 모른다.
#   그래서 정책을 **파일 하나**로 떼고 시험으로 잠근다.
#
# 🔑 정책 — 그리고 왜 그렇게 정했나:
#   rc=0 → 초록.
#   rc=1 → 빨강. (실패는 CI 가 막아야 하는 것)
#   rc=2 → **초록 개수를 보고 가른다.**
#     · 초록이 충분하면 → 초록 + `::warning::`
#       CI 에서 구조적으로 못 재는 검사가 있다(systemd 유닛·코어 체크아웃·로컬 도구).
#       그걸 빨강으로 만들면 **첫날부터 빨간불이 정상**이 되고 진짜 회귀가 그 안에 묻힌다.
#     · 초록이 모자라면 → 빨강.
#       rc=2 의 다른 원인이 **"아무것도 안 돌았다"** 이기 때문이다. 그 둘을 같은 칸에 두면
#       시험이 전부 사라진 상태가 경고 하나로 지나간다 — 이 배선이 없애려던 바로 그 상태다.
#   rc=그 외 → 빨강. 러너가 정의하지 않은 코드는 판정이 아니라 사고다.
#
# ⚠️ 초록 개수를 **못 읽으면 빨강**이다. "못 읽었다" 를 초록으로 만들면 이 스크립트가
#    자기 자신에게 조용한 초록을 허용하는 셈이 된다.
#
# 사용법:
#   scripts/ci-verdict.sh --rc <러너 종료코드>
#   scripts/ci-verdict.sh --rc 2 --out <러너 출력 파일> --min-green <N>   ← rc=2 면 둘 다 «필수»
#     ⚠️ 대괄호로 적지 않는다 — 「선택」으로 읽히면 그 오해는 **rc=2 가 처음 나는 날에만** 터지고,
#        그날은 이미 이상한 날인데 판정기까지 죽는다. (룬드 리뷰)
#     --min-green  rc=2 를 경고로 넘길 최소 초록 개수. **rc=2 면 필수** — 기본값을 두지 않는다.
#
# 🔴 왜 기본값이 없나 (룬드 리뷰, 2026-08-02):
#   이 파일이 스스로 내건 원칙이 「'못 읽었다' 를 초록으로 만들지 않는다」인데,
#   기본값은 **'안 준 것' 을 값으로 메워서** 통과 쪽으로 기울인다. 같은 파일 안에서
#   `--out` 부재는 빨강인데 `--min-green` 부재만 조용히 5 가 되던 것이라 자기모순이었다.
#   ⇒ 호출부가 **자기 분모를 말하게** 강제한다. 기본값이 있으면 아무도 안 준 채 굳는다.
#
# ⚠️ 알려진 한계 (후속) — `--min-green` 은 **절대 개수**라 레포 규모와 무관하다.
#   시험 25개짜리에서 초록이 6개만 남아도 `6 ≥ 5` 로 통과한다. 즉 「아무것도 안 돌았다」의
#   **부분 판**(19개가 사라진 상태)이 열려 있고, 전부 사라져야만 잡힌다. 축은 절대 개수가
#   아니라 **직전 실행 대비**여야 하는데 그건 상태가 필요해 이 파일 밖이다. (룬드 지적)
set -uo pipefail

RC=""
OUT=""
MIN_GREEN=""

die() { echo "❌ ci-verdict: $1"; exit 1; }   # 인자 사고도 빨강 — 조용히 통과시키지 않는다

while [ $# -gt 0 ]; do
    case "$1" in
        --rc)        [ $# -ge 2 ] || die "--rc 값 없음"; RC="$2"; shift 2 ;;
        --out)       [ $# -ge 2 ] || die "--out 값 없음"; OUT="$2"; shift 2 ;;
        --min-green) [ $# -ge 2 ] || die "--min-green 값 없음"; MIN_GREEN="$2"; shift 2 ;;
        # 머리말 끝을 `set` 줄로 «유도»한다 — 줄 번호를 손으로 적으면 주석이 자라는 순간 낡는다
        -h|--help)   sed -n '2,${/^set /q; p;}' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *)           die "모르는 인자: $1" ;;
    esac
done

case "$RC" in
    ''|*[!0-9]*) die "--rc 가 숫자가 아니다: '$RC'" ;;
esac

if [ "$RC" -eq 0 ]; then
    echo "✅ 전부 통과 (rc=0)"
    exit 0
fi

if [ "$RC" -eq 1 ]; then
    echo "🔴 시험 실패 (rc=1) — CI 를 빨강으로 둔다"
    exit 1
fi

if [ "$RC" -ne 2 ]; then
    echo "🔴 러너가 정의하지 않은 종료코드 rc=$RC — 판정이 아니라 사고다"
    exit 1
fi

# rc=2 — 초록 개수로 가른다
[ -n "$OUT" ] || die "rc=2 인데 --out 이 없다. 초록 개수를 못 세면 가를 수 없다"
[ -f "$OUT" ] || die "rc=2 인데 출력 파일이 없다: $OUT"
# 🔴 부재를 값으로 메우지 않는다 — 위 머리말의 이유. `--out` 부재와 «같은 층»에서 죽는다
[ -n "$MIN_GREEN" ] || die "rc=2 인데 --min-green 이 없다. 기본값을 두면 호출부가 자기 분모를 안 말한다"
case "$MIN_GREEN" in
    ''|*[!0-9]*) die "--min-green 이 숫자가 아니다: '$MIN_GREEN'" ;;
esac

# 🔑 `^` 로 앵커한다 — 앵커가 없으면 하위 시험이 자기 요약을 «들여쓴 채» 찍어도 매치되고,
#    그때는 `tail -1` 이 «순서» 로 구해주는 셈이 된다(형식이 아니라 순서에 의존). 러너는
#    자기 요약만 열 0 에서 찍으므로 앵커가 그 계약을 그대로 읽는다.
GREEN="$(sed -n 's/^── 결과: 통과 \([0-9][0-9]*\).*/\1/p' "$OUT" | tail -1)"
if [ -z "$GREEN" ]; then
    echo "🔴 rc=2 인데 초록 개수를 못 읽었다 — '못 읽었다' 를 초록으로 만들지 않는다"
    echo "   (러너 출력에 '── 결과: 통과 N' 줄이 있어야 한다)"
    exit 1
fi

if [ "$GREEN" -ge "$MIN_GREEN" ]; then
    echo "::warning::판정 불가가 있다 — CI 에서 구조적으로 못 재는 검사(초록 ${GREEN}개는 확인됨)"
    echo "⚠️ rc=2 · 초록 ${GREEN}개 ≥ 기준 ${MIN_GREEN} → 초록으로 두고 경고만 남긴다"
    # 🔴 제목 줄부터 **끝까지** 옮긴다. 치환이 자기 자신이던 옛 판은 제목 한 줄만 찍었다.
    #    rc=2 를 초록으로 넘기는 근거가 「구조적으로 못 재는 검사가 있다」인데,
    #    **무엇을 못 쟀는지 안 남기면 그 근거를 확인할 자리가 없다.** 게다가 러너의
    #    `🔴 새로 못 재게 됐다:` 줄이 「원래 못 재는 것」과 「새로 못 재게 된 것」을 갈라주는데,
    #    그 줄을 버리면 **봐줘도 되는 rc=2 와 봐주면 안 되는 rc=2 를 구별할 정보를 스스로 버린다.**
    sed -n '/^   판정 불가:/,$p' "$OUT"
    exit 0
fi

echo "::error::판정 불가인데 초록이 ${GREEN}개뿐이다 — 시험이 안 돌았을 가능성"
echo "🔴 rc=2 · 초록 ${GREEN}개 < 기준 ${MIN_GREEN} → 빨강. '아무것도 안 돌았다' 와 구별할 수 없다"
exit 1
