#!/usr/bin/env bash
# 코어 드리프트 시간별 점검 — cron 래퍼 (승인 ③, Darren 2026-07-28 M:c3rg)
#
# 🔑 이 래퍼의 계약은 **언제 소리를 내는가** 하나다:
#   rc=0 충족    → 조용. 대신 **하트비트를 남긴다**(안 돌고 있는 것과 구분하려고)
#   rc=1 위반    → 알린다 (조치가 있다: pull 또는 재시작)
#   그 외        → **알린다**. "판정 불가"를 조용히 넘기면 *괜찮음*과 같아지고,
#                  없는 경고는 pull 을 미루게 해서 옛 코드로 계속 돌게 만든다.
#
# 🔑 종료코드 계약 (2026-07-28 양봇 합의 — 코어 run-tests 계열로 통일):
#     0 정상 · 1 위반(조치 있음) · 2 판정 불가 · **그 외(126·127·128+) ⇒ 판정 불가(2)로 접는다**
#   ⚠️ 마지막 항이 핵심이다. 126/127 은 **도구가 고른 값이 아니라 셸이 낸다** — 그래서 어떤
#      도구 헤더에도 안 적히고, 부르는 쪽이 `case 0|1|2` 로만 쓰면 default 로 조용히 샌다.
#      이전엔 `exit "$RC"` 로 원본을 그대로 통과시켜서, 화면엔 "판정 불가"라고 쓰면서
#      **종료코드는 127** 이 나갔다 — 말과 코드가 어긋난 상태(시험 ⑧이 잠근다).
#
# ⚠️ 하트비트가 필요한 이유: 이 cron 자체가 죽으면 출력이 없다 = rc=0 과 같은 모양이다.
#    무음이 "드리프트 없음"을 뜻하려면 **이 스크립트가 살아 있다는 증거**가 따로 있어야 한다.
#    지금은 파일 mtime 으로 남기고, 그 신선도를 보는 쪽은 아직 없다 → TODO(아래).
#
# TODO(승인 ③ 후속): 하트비트가 2시간 이상 낡으면 아침 브리핑에서 경고. 지금은 파일만 남긴다.
#    묻어두지 않으려고 여기 적는다 — 이게 없으면 "cron 이 죽은 상태"가 여전히 무음이다.
set -uo pipefail

BOT_DIR="${BOT_DIR:-$HOME/discord-bot-nino}"
CHECK="${CHECK:-$BOT_DIR/scripts/check-core-drift.sh}"
HEARTBEAT="${HEARTBEAT:-$BOT_DIR/logs/core-drift.heartbeat}"
LOG="${LOG:-$BOT_DIR/logs/core-drift.log}"
NOTIFY_TARGET="${NOTIFY_TARGET:-봇-놀이터}"
DISCORD_SEND="${DISCORD_SEND:-$BOT_DIR/src/discord-send}"

[ -f "$BOT_DIR/.env" ] && { set -a; . "$BOT_DIR/.env"; set +a; }
mkdir -p "$(dirname "$HEARTBEAT")"

# ── 인자 계약 ────────────────────────────────────────────────────────────────
# 🔴 옛 형태는 `DRY_RUN="${DRY_RUN:-0}"` 였다 — **환경에서 물려받는** dry-run 이고,
#   하필 **바로 다음 줄에서 `set -a; . .env`** 를 한다. 누가 `.env` 에 한 줄 넣으면
#   이 감시기는 **발송 0건 · rc=0** 으로 조용히 멈추고 성공처럼 보인다.
#   (오늘 `.env`·crontab 둘 다 `DRY_RUN` 을 안 준다고 실측했다 — 사고가 아니라 **형태**를 없앤다.)
#   🔑 무시하면 dry-run 을 기대한 쪽이 발송당하고, 따르면 발송을 기대한 쪽이 조용해진다.
#     **어느 쪽으로 접어도 조용히 틀린다** — 거절만이 두 오독을 다 막는다(코어 계약 ④).
#   ⇒ 켜는 길은 **플래그 하나**뿐이다: `--dry-run`.
cli_guard_usage() {
    echo "usage: $(basename "$0") [--dry-run] [-h|--help]"
    echo "  --dry-run   판정까지 하되 Discord 발송은 하지 않는다 (진단용)"
}
# 🔑 거절도 로그 1줄로 남긴다. cron 은 stderr 를 버리므로, 안 남기면 crontab 오타 하나로
#   이 감시기가 **아무 표시 없이** 멈춘다 — 감시기가 조용히 죽는 그 형태 그대로다.
cli_guard_reject_log() {
    printf '%s verdict=%s rc=2\n' "$(date '+%Y-%m-%dT%H:%M:%S%z')" "$1" >> "$LOG" 2>/dev/null || true
}
CLI_GUARD_ON_REJECT=cli_guard_reject_log
# 🔴 배선은 **스크립트 자기 위치**에서 찾는다 — `$BOT_DIR` 로 찾으면 안 된다.
#   `BOT_DIR` 는 *데이터*(logs·state)를 옮기는 손잡이라 시험이 임시 디렉터리로 바꾼다.
#   거기서 *코드*를 찾게 했더니 시험 8건이 `No such file` 로 깨졌다.
#   🔑 **주입점을 하나로 쓰면 두 축이 같이 움직인다** — 코드와 데이터는 다른 축이다.
CLI_GUARD_LIB_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
. "$CLI_GUARD_LIB_DIR/lib/cli-guard-boot.sh"
cli_guard_boot "$@"

OUT="$("$CHECK" 2>&1)"; RC=$?
STAMP="$(TZ=Asia/Seoul date '+%Y-%m-%d %H:%M:%S')"

# 🔑 **로그는 판정만이 아니라 근거를 남긴다.** 이전엔 `head -1` 이라 첫 줄만 남았는데,
#    버려지던 게 rc 가 아니라 **왜** 였다(2026-07-28 실측 — 4줄 중 3줄):
#      DRIFT: repo_behind=1커밋 …            ← 남음
#        런타임 파일 변경: 0건                ← 버림  = 재시작 필요 여부의 근거
#        ✅ 받아도 설정 요건 충족             ← 버림  = 최종 판정
#    그날 Darren 승인을 받으며 내가 댄 근거가 정확히 저 버려지는 줄이라, 로그만으로는
#    *"그때 왜 재시작 안 했지"* 를 되짚을 수 없었다.
# ⚠️ 헤드라인 **형식은 안 바꾼다** — 이력을 날짜로 세는 쪽이 깨지면 "언제부터 밀렸나" 를
#    못 세게 되고, 그건 이 수정이 지키려는 것과 같은 것을 부순다. 이어지는 줄은
#    **들여쓰기**로 붙여 헤드라인 집계(`grep -cE '^[0-9]{4}-'`)를 그대로 둔다.
printf '%s rc=%s %s\n' "$STAMP" "$RC" "$(printf '%s' "$OUT" | head -1)" >> "$LOG"
printf '%s' "$OUT" | tail -n +2 | sed 's/^ *//; s/^/    · /' >> "$LOG"
printf '%s rc=%s\n' "$STAMP" "$RC" > "$HEARTBEAT"

# 충족이면 여기서 끝 — 조용한 게 정상이고, 살아 있다는 증거는 하트비트가 댄다
# 🔴 알림은 **사실이 아니라 변화**로 보낸다 (2026-07-29, 룬드 지적 · Darren 승인 M:x9mo)
#   실사고: 이 래퍼가 **하루 30건**을 보냈다(매시 :15, 전부 동일 문구).
#   내용은 *"2커밋 뒤처졌다"* 인데 그건 **승인 대기로 일부러 안 당기는 상태**였다.
#   ⇒ 조치가 불가능한 구간에서 같은 말을 반복한 것이고, 그건 순수 소음이다.
# 🔑 거짓/무의미 호출이 반복되면 사람이 알림을 끈다 — 그러면 진짜가 왔을 때 묻힌다.
#   워치독 Check 4 에 이미 적어둔 논리인데 **이 파일에 옮겨 적용하지 않았다**(교훈은 파일 단위로 갇힌다).
# 🔴 그리고 **급한 것과 안 급한 것이 안 갈렸다** — 30건 전부 `process_behind=0`(재시작 불필요)인데
#   실행 파일이 바뀐 날에도 문구가 같았을 것이다. ⇒ 아래 FORCE 가 그 자리를 가른다.
NOTIFY_STATE="${NOTIFY_STATE:-$BOT_DIR/logs/core-drift-notify-state}"
RENOTIFY_AFTER="${RENOTIFY_AFTER:-43200}"   # 12시간 — 같은 상태여도 이만큼 지나면 한 번 더 부른다
                                            # 🔑 **영영 잊지는 않는다.** 순수 침묵은 조치를 영원히 미룬다.

# 해소되면 상태를 지운다 — 재발했을 때 **즉시** 부를 수 있어야 한다
if [ "$RC" -eq 0 ]; then
    rm -f "$NOTIFY_STATE"
    exit 0
fi

if [ "$RC" -eq 1 ]; then
    HEAD="🔴 코어 드리프트 — 조치 필요"
    OUT_RC=1
else
    # rc=2·126·127 등: 판정이 안 된 것이지 괜찮은 게 아니다
    # 🔑 **접되 왜 접었는지는 남긴다.** 접기만 하면 *도구가 없다*·*중간에 죽었다*·*권한*
    #    셋이 한 문장이 되어, 오늘 `head -1` 이 근거를 버린 것과 같은 자리가 된다(룬드 지적).
    #    ⚠️ 추측이 아니다 — 셸이 코드로 **이미 구분해 준다.** 그대로 옮겨 적기만 하면 된다:
    #      126 실행 권한 없음 · 127 명령을 못 찾음 · 128+N 시그널 N 으로 죽음
    case "$RC" in
        2)   WHY="" ;;
        126) WHY=" — 실행 권한 없음(chmod +x 확인)" ;;
        127) WHY=" — 명령을 못 찾음(cron PATH 는 /usr/bin:/bin 뿐이다)" ;;
        13[0-9]|12[89]|1[4-9][0-9])
             WHY=" — 시그널 $((RC - 128)) 로 죽음(중간에 끊겼다)" ;;
        # 🔸 3~125 는 **셸의 몫이 아니다.** 룬드가 코어 #94 에서 좁혔고 근거가 맞다:
        #    `mutate.sh` 는 `3=판정 불가`·`4=복구 실패(레포에 변이가 남았다)` 를 **쓰고 있어서**,
        #    "그 외 전부 접기"로 하면 4 가 뭉개져 *변이가 남은 걸 못 본다*. 내 원안이 넓었다.
        #    ⇒ 공용 계약의 접기 대상은 **셸이 소유한 코드(126·127·128+)뿐**이다.
        # ⚠️ 아래 `*` 는 **이 래퍼만의 지역 판단**이지 공용 규칙이 아니다 — 이 래퍼의 호출
        #    대상(check-core-drift.sh)은 계약이 0/1/2 뿐이라 3~125 는 *약속에 없는 값*이고,
        #    그건 "못 쟀다"로 읽는 게 맞다. 계약이 3·4 를 쓰는 호출자는 접으면 안 된다.
        *)   WHY=" — 계약에 없는 코드다(호출 대상은 0/1/2 만 낸다)" ;;
    esac
    HEAD="⚠️ 코어 드리프트 **판정 불가** (rc=$RC)$WHY — 검사가 못 돌았다"
    # 🔑 **모르는 코드는 모른다고 낸다.** 원본을 그대로 흘리면 부르는 쪽의 `case 0|1|2` 가
    #    default 로 빠져 조용해진다. 정상(0)으로도 위반(1)으로도 접지 않고 2 로 모은다.
    OUT_RC=2
fi

MSG="$HEAD
\`\`\`
$OUT
\`\`\`"

# ── 억제 판단 ─────────────────────────────────────────────────────────────
# 🔑 **억제하는 것은 알림뿐이다.** 종료코드(OUT_RC)는 그대로 나간다 —
#   조용해졌다고 판정이 바뀐 게 아니다. cron 이 rc 로 상태를 읽는 걸 망가뜨리면 안 된다.
NOW="$(date +%s)"
SIG="$RC|$(printf '%s' "$OUT" | md5sum 2>/dev/null | cut -c1-12)"

# 🔴 **실행 파일이 바뀌었으면 억제하지 않는다** — 그건 재시작이 필요한 상태다.
#   억제를 넣을 때 제일 위험한 실패 모드가 **급한 것까지 같이 잠기는 것**이다(룬드 리뷰 요청).
PROC_BEHIND="$(printf '%s' "$OUT" | sed -n 's/.*process_behind=\([0-9]\{1,\}\).*/\1/p' | head -1)"
FORCE=0
case "${PROC_BEHIND:-}" in
    ''|0) ;;                 # 0 이거나 못 읽었으면 평소 규칙
    *)    FORCE=1 ;;         # 1 이상 = 런타임이 어긋났다 = 매번 부른다
esac
# 🔑 판정 불가(rc≠1)도 억제하지 않는다 — 그건 **검사기가 못 돈 것**이라
#   "같은 상태가 이어진다" 로 접으면 죽은 검사가 조용해진다.
[ "$RC" -eq 1 ] || FORCE=1

if [ "$FORCE" -eq 0 ]; then
    PREV_SIG=""; PREV_AT=0
    # 🟡 못 읽거나 깨졌으면 **부르는 쪽**으로 간다 — 못 부른 사고가 헛부름보다 비싸다.
    if [ -r "$NOTIFY_STATE" ]; then
        read -r PREV_SIG PREV_AT < "$NOTIFY_STATE" 2>/dev/null || { PREV_SIG=""; PREV_AT=0; }
        case "${PREV_AT:-}" in ''|*[!0-9]*) PREV_SIG=""; PREV_AT=0 ;; esac
    fi
    if [ -n "$PREV_SIG" ] && [ "$PREV_SIG" = "$SIG" ] \
       && [ "$(( NOW - PREV_AT ))" -lt "$RENOTIFY_AFTER" ]; then
        # 같은 상태가 이어지는 중 — 로그엔 이미 남았다(위). 알림만 접는다.
        exit "$OUT_RC"
    fi
fi
printf '%s %s\n' "$SIG" "$NOW" > "$NOTIFY_STATE"

if [ "$CLI_DRY_RUN" = "1" ]; then
    # 🔸 **보낼 뻔한 것을 stdout 으로 보여준다.** 코어의 `cli_guard_send` 안내는 stderr 라
    #   파이프로 못 받는다 — dry-run 은 *보려고* 부르는 것이라 본문이 필요하다.
    printf '%s\n' "$MSG"
    exit "$OUT_RC"
fi

# 🔑 위 갈래가 먼저 잡으므로 dry-run 일 때 여기 **도달하지 않는다.** 그래도 감싸는 이유는,
#   저 갈래가 언젠가 지워지거나 발송 자리가 하나 더 생겨도 **계약이 남게** 하려는 것이다.
#   ⇒ 억제의 정본은 `cli_guard_send` 이고 위 갈래는 *가시성*이다. (변이로 확인: 갈래를 지워도 발송 0)
cli_guard_send "$DISCORD_SEND" "$NOTIFY_TARGET" "$MSG"
exit "$OUT_RC"
