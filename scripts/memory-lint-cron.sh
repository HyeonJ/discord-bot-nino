#   — **원장에 한 번도 안 나타난 결함**이다. 같은 자리를 여기 만들지 않는다.
NOW="${MEMORY_LINT_NOW:-$(date +%s)}"
# 임계·재알림 간격(시간).
# 🔴 **이 24 는 «내가 고른 값»이다 — Darren 값이 아니다.** 승인(`M:1ctw`)은 **기능**에 대한
#   것이고 시간은 안 물었다. 「env 로 열어뒀다」가 「사람이 정했다」를 대신하지 않는다 —
#   **env 를 안 걸면 기본값이 곧 운영값**이다(룬드 `#174` 리뷰). 방향이 안전해도 자작은 자작이라
#   그렇다고 적어둔다. Darren 이 값을 주면 여기에 `M:` 를 병기하고 이 문단을 지운다.
