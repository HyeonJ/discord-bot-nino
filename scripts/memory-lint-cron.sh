# ── 인자 계약 ────────────────────────────────────────────────────────────────
# 🔴 옛 형태는 `DRY_RUN="${DRY_RUN:-0}"` 였다 — **환경에서 물려받는** dry-run 이고, 하필
#   **바로 위 줄에서 `set -a; . .env`** 를 한다. `.env` 에 한 줄 들어가면 이 감시기는
#   **발송 0건 · rc=0** 으로 조용히 멈추고 성공처럼 보인다. 게다가 인자 파싱이 없어서
#   `DRY_RUN` 은 **환경으로만** 켤 수 있었다 — 끄는 길이 플래그로 존재하지도 않았다.
#   🔑 어느 쪽으로 접어도 조용히 틀린다 — 거절만이 두 오독을 다 막는다(코어 계약 ④).
cli_guard_usage() {
    echo "usage: $(basename "$0") [--dry-run] [-h|--help]"
    echo "  --dry-run   판정까지 하되 Discord 발송은 하지 않는다 (진단용)"
}
# 🔑 거절도 로그 1줄로 남긴다 — cron 은 stderr 를 버리므로 안 남기면 crontab 오타 하나에
#   이 감시기가 아무 표시 없이 멈춘다.
cli_guard_reject_log() {
    printf '%s verdict=%s rc=2\n' "$(TZ=Asia/Seoul date '+%Y-%m-%d %H:%M:%S')" "$1" >> "$LOG" 2>/dev/null || true
}
CLI_GUARD_ON_REJECT=cli_guard_reject_log
# 🔴 배선은 **스크립트 자기 위치**에서 찾는다 — `$BOT_DIR` 는 *데이터*(logs·state)를 옮기는
#   손잡이라 시험이 임시 디렉터리로 바꾼다. 거기서 코드를 찾게 했더니 시험 8건이 깨졌다.
#   🔑 주입점 하나로 두 축(코드·데이터)을 같이 움직이면, 한 축을 흔들 때 다른 축이 따라온다.
CLI_GUARD_LIB_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
. "$CLI_GUARD_LIB_DIR/lib/cli-guard-boot.sh"
cli_guard_boot "$@"

# 🔑 **키는 검사기가 준다** — 여기서 문자열을 정규화하지 않는다 (코어 #141, 2026-08-02).
#   `LINT_KEY_FILE` 은 **append** 라 계약상 «매번 새 파일»을 줘야 한다. 재사용하면 지난 실행의
#   키가 섞여 「새 항목」이 영영 안 나온다 — 조용한 쪽으로 틀린다.
KEYFILE="$(mktemp "${TMPDIR:-/tmp}/memory-lint-keys.XXXXXX")"
trap 'rm -f "$KEYFILE"' EXIT
export LINT_KEY_FILE="$KEYFILE"

# ⚠️ 파이프를 끼우지 않는다 — `cmd | tail` 뒤의 $? 는 tail 의 코드다(오늘 네 번 걸린 자리).
OUT="$("$LINT" 2>&1)"; RC=$?
STAMP="$(TZ=Asia/Seoul date '+%Y-%m-%d %H:%M:%S')"

# 항목 추출: 검사가 내는 "  ⚠️  <내용>" 줄만. 요약줄·섹션 헤더는 상태로 쓰지 않는다.
# 🔴 **정렬하지 않는다.** 키 파일은 `issue()` 호출 순서로 쌓이므로 사람 줄과 **행 단위로 짝**이다.
#   여기서 `sort -u` 를 하면 그 짝이 어긋나 **엉뚱한 항목이 엉뚱한 키로 판정된다**(옛 판엔 있었다).
CURRENT="$(printf '%s\n' "$OUT" | sed -n 's/^  ⚠️  //p')"
COUNT="$(printf '%s' "$CURRENT" | grep -c . || true)"
KEYS="$(cat "$KEYFILE" 2>/dev/null)"
KEYCOUNT="$(printf '%s' "$KEYS" | grep -c . || true)"

printf '%s rc=%s 항목=%s\n' "$STAMP" "$RC" "$COUNT" >> "$LOG"
printf '%s rc=%s 항목=%s\n' "$STAMP" "$RC" "$COUNT" > "$HEARTBEAT"

notify() {  # $1=본문
  # 🔸 dry-run 이면 **보낼 뻔한 본문을 stdout 으로** 보여준다. 코어 안내는 stderr 라 파이프로
  #   못 받는데, dry-run 은 *보려고* 부르는 것이라 본문이 필요하다.
  # 🔴 **억제와 가시성을 갈라 둔다.** 처음엔 이 갈래가 `return 0` 까지 해서 억제도 같이 했는데,
  #   그러면 억제 기제가 **두 벌**이 되고 변이시험이 잡았다 — `cli_guard_send` 를 직접 발송으로
  #   바꿔도 **0 fail**(갈래가 가려서 계약 쪽은 아무 시험도 안 밟는다).
  #   🔑 사본이 둘이면 하나가 죽어도 안 보인다. ⇒ 갈래는 본문만 내고 안 보내는 일은 계약이 한다.
  [ "$CLI_DRY_RUN" = "1" ] && printf '%s\n' "$1"
  cli_guard_send "$DISCORD_SEND" "$NOTIFY_TARGET" "$1"
}

# 🔑 판정 불가를 먼저 가른다 — 0건(rc=0)도 아니고 항목 있음(rc=1)도 아닌 상태.
#    여기서 조용히 넘기면 "검사가 죽은 것"이 "문제 없음"과 같은 모양이 된다.
if [ "$RC" -ne 0 ] && [ "$RC" -ne 1 ]; then
  notify "⚠️ 기억 검사 **판정 불가** (rc=$RC) — 검사가 못 돌았다
\`\`\`
$(printf '%s' "$OUT" | tail -15)
\`\`\`"
  exit "$RC"
fi

# 🔴 «같은 항목인가»는 항목 문자열 그대로가 아니라 **정규화한 키**로 본다 (2026-08-02).
#   실사고: `🚨 1000줄 초과: inbox-…md (6627줄)` 의 **줄 수가 항목 이름 안에** 있었다.
#   그 파일에 한 줄 쓸 때마다 6627→6667 로 문자열이 바뀌어 **같은 문제가 매시 「새 항목」**이 됐다.
#   Darren 이 「이거 왜 계속 보내?」로 잡았다.
#
# 🔑 아래 집합 비교는 «맞게» 돌고 있었다 — 틀린 건 한 층 아래, **원소의 식별자**다.
#   증거의 형태: 로그의 `항목=13` 이 8시간 내내 고정인데 알림은 왔다.
#   **개수가 안 변하는데 소리가 나면 그건 원소 「이름」이 바뀐 것이다.**
#
# 🔴 **문자열 정규화는 구조적으로 불가능했다**(폐기한 옛 처방). 「괄호 안」을 접으면 괄호 «밖»에
#   측정값을 둔 것들(목차 불일치·코드펜스 홀수·`N일 미수정`)이 남고, 「숫자+단위」를 전부 접으면
#   `500줄 초과`/`1000줄 초과` 가 같은 키가 되어 **한도를 넘어서는 순간이 조용해진다.**
#   ⇒ 배치를 쫓지 말고 **내는 쪽이 키를 준다** (코어 `#141`, 최종 전수 26곳 중 키 14).
#
# 🔴 **분모 가드 — 「전부인가」층.** 사람 줄과 키가 **행 단위로 짝**이라는 게 이 비교의 전제다.
#   그 짝이 깨졌는데 그냥 돌면 **엉뚱한 항목을 엉뚱한 키로 판정**하고, 결과는 「조용」쪽으로 기운다
#   (모르는 키가 없어 보이니까). 검사기가 옛 판이면 키가 0건인데 **그것도 「새 항목 없음」과
#   같은 모양**이다. ⇒ 여기서 갈라 **판정 불가로 시끄럽게** 낸다.
if [ "$KEYCOUNT" -ne "$COUNT" ]; then
  notify "⚠️ 기억 검사 **판정 불가** — 항목 ${COUNT}건인데 키가 ${KEYCOUNT}건이다
검사기가 안정 키 채널(\`LINT_KEY_FILE\`)을 안 내고 있다 — 정본 클론이 낡았을 수 있다.
\`\`\`
$(printf '%s' "$OUT" | tail -8)
\`\`\`"
  echo "$STAMP 판정 불가 — 항목=$COUNT 키=$KEYCOUNT (키 채널 부재/불일치)" >> "$LOG"
  exit 2
fi

# 이전 집합과 비교. 상태 파일이 없으면 첫 실행이므로 현재 전부가 '새 항목'이다(1회 통보).
# 🔸 상태 파일에는 이제 **키**가 산다(사람 줄이 아니라). 첫 줄의 표지로 옛 형식과 가른다 —
#   옛 상태를 키로 읽으면 **13건이 통째로 「새 항목」**이 되어, 이 수리가 마지막으로 한 번
#   크게 우는 것으로 끝난다. Darren 이 잡은 그 소음을 고치면서 같은 소음을 내지 않는다.
# 🔸 v2 = `first_seen<TAB>last_notified<TAB>키`. v1 은 키만 있어 **나이를 모른다**.
STATE_MARK='#keys-v2'
STATE_MARK_V1='#keys-v1'
PREV=""            # v2 원본 줄(세 칸)
PREV_KEYS=""       # 키만 뽑은 것 — 「새 항목인가」 판정용
MIGRATED=0
if [ -f "$STATE" ]; then
  _head="$(head -1 "$STATE")"
  if [ "$_head" = "$STATE_MARK" ]; then
    PREV="$(tail -n +2 "$STATE")"
    PREV_KEYS="$(printf '%s\n' "$PREV" | cut -f3-)"
  else
    # 🔴 v1(키만) 도 사람 줄도 **나이를 모르는 건 같다**. Ⅰ「관측한 것만 안다」의 자리다 —
    #   없는 나이를 epoch 0 으로 채우면 전 항목이 즉시 「무한히 늙었다」가 되어 **한 번에 전부
    #   운다**(213건 소음의 재발). 게다가 그 나이는 **관측이 아니라 날조**다.
    #   ⇒ 전환 시점을 first_seen 으로 삼고, **그렇게 했다고 전환 통보에 적는다**.
    MIGRATED=1
    [ "$_head" = "$STATE_MARK_V1" ] && MIGRATED=2   # 2 = 키는 있었다(v1) / 1 = 사람 줄
  fi
fi

# prev 조회 — 연관배열을 안 쓴다(bash 3.2 에 없다. 룬드 맥이 그 판이고 공유 코어 후보다).
prev_field() {  # $1=키 $2=필드번호(1=first_seen 2=last_notified)
  printf '%s\n' "$PREV" | awk -F'\t' -v k="$1" -v f="$2" '$3 == k { print $f; exit }'
}

# 🔸 출력은 **현재 항목 원문**이다(측정값 포함) — 키는 판정용이고 사람이 읽는 건 실제 값이다.
#   순서도 lint 출력 순서를 그대로 둔다(옛 `comm` 은 정렬을 강제했다).
NEW_LINES=""
AGED_LINES=""      # 늙어서 «다시» 알릴 것 (이번 회차에 소리내는 것만)
AGED_KEYS=""       # 그 키들 — 상태 쓸 때 last_notified 를 미는 대상
UNREADABLE=""      # 상태엔 있는데 나이 칸을 못 읽은 키 (판정 불가 대상)
if [ "$MIGRATED" -eq 0 ]; then
  _i=0
  while IFS= read -r _l; do
      [ -n "$_l" ] || continue
      _i=$((_i + 1))
      _k="$(printf '%s\n' "$KEYS" | sed -n "${_i}p")"
      if ! printf '%s\n' "$PREV_KEYS" | grep -qxF -- "$_k"; then
          NEW_LINES="${NEW_LINES}${_l}
"
          continue
      fi
      # 이미 아는 항목 — 늙었나?
      _fs="$(prev_field "$_k" 1)"; _ln="$(prev_field "$_k" 2)"
      # 🔴 **상태에 «있는데» 나이를 못 읽으면 «판정 불가»다** (룬드 `#174` 리뷰).
      #   옛 판은 여기서 `continue` 했는데, 그게 **이 스크립트에서 「모르면 조용」인 유일한 자리**였다
      #   — 나머지는 전부 시끄러운 쪽으로 실패한다. 게다가 조용히 넘기면 `write_state` 가
      #   `_f="$NOW"` 로 **나이를 리셋**해서 그 항목은 **영원히 임계를 못 넘는다**:
      #   이 기능이 없애려던 무음이 그대로 돌아오고, 완전 무음이다.
      # 🔑 좌변을 맞추는 것(`cut -f3` 로 통일)은 **「지금 이 형식에서만」 참**이라, 형식이 또 오르면
      #   같은 자리가 다시 열린다. 판정 불가로 떨어뜨리면 **형식과 무관하게 산다.**
      if [ -z "$_fs" ]; then
          UNREADABLE="${UNREADABLE}${_k}
"
          continue
      fi
      [ -n "$_ln" ] || _ln="$_fs"
      _age=$((NOW - _fs))
      _since=$((NOW - _ln))
      # 🔑 두 조건이 **둘 다** 필요하다: 늙었나(_age) · 최근에 안 떠들었나(_since).
      #   앞엣것만 두면 임계를 넘는 순간부터 **매시** 운다 — 그게 이 스크립트가 막으려던 소음이다.
      if [ "$_age" -ge "$AGE_SEC" ] && [ "$_since" -ge "$RENOTIFY_SEC" ]; then
          AGED_LINES="${AGED_LINES}${_l}  ← $((_age / 3600))시간째
"
          AGED_KEYS="${AGED_KEYS}${_k}
"
      fi
  done <<EOF_CUR
$CURRENT
EOF_CUR
fi
NEW="$(printf '%s' "$NEW_LINES" | grep -c . || true)"
AGED="$(printf '%s' "$AGED_LINES" | grep -c . || true)"
UNREAD_N="$(printf '%s' "$UNREADABLE" | grep -c . || true)"

# 🔑 **`write_state` 를 가드«보다 위»에 둔다.** 원래는 가드가 정의 «전»에 있었는데, 그러면
#   그 구간에서 `write_state` 를 부르는 실수가 `set -uo pipefail`(-e 없음) 아래서 **조용히
#   아무 일도 안 한다** — 변이시험에서 실제로 드러났다(그 변이가 «살아남은» 게 아니라
#   **성립 불가**였다. 🔴 둘은 다르다: 살아남으면 «시험 구멍»이고, 성립 불가면 **그 변이가
#   아무것도 안 잰 것**이라 초록이 아무 뜻이 없다). 순서를 바꿔 그 구간을 없앤다.
# 🔴 상태 쓰기가 **세 칸**을 유지한다. 규율은 그대로 — «알림에 성공했을 때만» 부른다.
#   🔑 `last_notified` 는 **이번에 실제로 소리낸 것만** 민다. 늙었는데 소리를 못 냈으면
#      옛 값이 남아 다음 회차에 다시 시도한다 — *「조치했다」가 「해소했다」를 대신하지 않게*.
write_state() {
  {
    printf '%s\n' "$STATE_MARK"
    _j=0
    while IFS= read -r _k; do
      [ -n "$_k" ] || continue
      _j=$((_j + 1))
      _f="$(prev_field "$_k" 1)"
      [ -n "$_f" ] || _f="$NOW"                       # 처음 보는 것 = 지금부터 센다
      _l="$(prev_field "$_k" 2)"
      [ -n "$_l" ] || _l="$NOW"
      printf '%s\n' "$AGED_KEYS" | grep -qxF -- "$_k" && _l="$NOW"
      printf '%s\t%s\t%s\n' "$_f" "$_l" "$_k"
    done <<EOF_KEYS
$KEYS
EOF_KEYS
  } > "$STATE"
}

# 🔴 판정 불가는 **상태를 갱신하기 «전»에** 낸다 — 갱신하면 그 키의 나이가 지금으로 리셋돼서
#   다음 회차엔 「정상」처럼 보인다(고장이 자기 흔적을 지운다).
if [ "$UNREAD_N" -gt 0 ]; then
  notify "⚠️ 기억 검사 **판정 불가** — 상태에 있는 항목 ${UNREAD_N}건의 **나이를 못 읽었다**
상태 파일의 칸 구분과 키 형식이 어긋났다(키에 탭이 섞였을 때 그렇다). 그대로 두면 그 항목은 **나이가 매 회차 리셋돼 영원히 안 늙는다**.
\`\`\`
$(printf '%s' "$UNREADABLE" | head -5)
\`\`\`"
  echo "$STAMP 판정 불가 — 나이 미해독 ${UNREAD_N}건 (상태 미갱신)" >> "$LOG"
  exit 2
fi


# 🔴 **전환은 «한 줄로» 알린다** (룬드 실증, 2026-08-02).
#   처음엔 여기서 조용히 넘겼다. 그런데 삼키는 건 「이미 알린 것」만이 아니다 —
#   **전환 시점에 처음 나타난 항목도 같이 기준선에 들어가서, 해소됐다 다시 생기기 전엔
#   영영 안 알린다.** 「1회 소음 방지」가 아니라 **그 시점의 미발견 문제를 영구 매장**이다.
#   실증(룬드): 전환 회차 0건 · **다음 회차도 0건**(새 키가 기준선에 삼켜져 있다).
# 🔑 이 스크립트의 나머지는 전부 **시끄러운 쪽으로 실패**하는데(판정 불가 → 알림 + rc=2)
#   여기만 반대였다. 피하려던 건 「전 항목 통째 나열」이고, **한 줄은 그게 아니다.**
# 🔸 그리고 전환이 **보인다** — 로그에만 남기면 아무도 안 본다.
if [ "$MIGRATED" -ne 0 ]; then
  # 🔴 **무엇을 «모르는지»를 통보에 적는다.** 안 적으면 다음 사람이 이 시점의 나이를 «진짜 나이»로
  #   읽는다 — 「15시간 방치」를 재려고 만든 기능이 첫 날부터 틀린 수를 낸다.
  if [ "$MIGRATED" -eq 2 ]; then
    _mig_msg="🔸 기억 검사 — 상태에 **나이 칸**을 붙였다(키 → 키+시각). 현재 ${COUNT}건의 나이는 **지금부터** 센다 — 옛 상태엔 «언제 처음 봤나»가 없어서 그 전 기간은 **모르는 것**이고, 지어내지 않는다. 늙음 알림은 ${AGE_ALERT_HOURS}시간 뒤부터."
    _mig_log="상태 형식 전환(키 → 키+나이) — ${COUNT}건, 나이 기준점=$NOW, 1줄 통보"
  else
    _mig_msg="🔸 기억 검사 — 항목 식별 방식을 바꿨다(사람 줄 → **안정 키**). 현재 ${COUNT}건을 기준선으로 삼는다. 새 항목 알림은 다음 회차부터. 나이는 **지금부터** 센다."
    _mig_log="상태 형식 전환(사람 줄 → 키+나이) — ${COUNT}건을 기준선으로, 1줄 통보"
  fi
  if notify "$_mig_msg"; then
    write_state
    echo "$STAMP $_mig_log" >> "$LOG"
    exit 0
  fi
  # 통보가 실패했으면 상태를 갱신하지 않는다 — 아무도 모르는 채로 기준선이 잡히면 안 된다(⑧과 같은 규율).
  echo "$STAMP 전환 통보 실패 — 상태를 갱신하지 않는다(다음 회차에 다시 시도)" >> "$LOG"
  exit 3
fi

# 상태는 **비교 후 항상** 갱신한다. 알림 실패와 무관하게 갱신하면 다음 회차에 조용해지므로,
# 알림을 보내는 경우에만 갱신한다 — "조치했다"가 "해소했다"를 대신하지 않게.
if [ "$NEW" -eq 0 ] && [ "$AGED" -eq 0 ]; then
  # 새 항목도 늙은 항목도 없음 = 조용. 상태만 최신화(해소된 항목 반영)
  write_state
  exit 0
fi

# 🔑 **두 갈래를 한 메시지에 «갈라» 싣는다** — 「새로 생겼다」와 「안 줄고 있다」는 처방이 다르다.
#   한 덩어리로 부으면 읽는 쪽이 그 구별을 다시 해야 하고, 그러면 늙은 것이 새 것 사이에 묻힌다.
MSG="🔸 기억 검사"
[ "$NEW" -gt 0 ] && MSG="$MSG — **새 항목 ${NEW}건**"
[ "$AGED" -gt 0 ] && MSG="$MSG — **늙은 항목 ${AGED}건**"
MSG="$MSG (전체 ${COUNT}건)"
if [ "$NEW" -gt 0 ]; then
  MSG="$MSG
**새 항목**
\`\`\`
$(printf '%s' "$NEW_LINES")
\`\`\`"
fi
if [ "$AGED" -gt 0 ]; then
  MSG="$MSG
**${AGE_ALERT_HOURS}시간 넘게 안 줄고 있는 것**
\`\`\`
$(printf '%s' "$AGED_LINES")
\`\`\`"
fi
if notify "$MSG"; then
  write_state
else
  echo "$STAMP 알림 전송 실패 — 상태를 갱신하지 않는다(다음 회차에 다시 알린다)" >> "$LOG"
  exit 3
fi
exit 0
