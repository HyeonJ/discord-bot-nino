#!/usr/bin/env bash
# capture-rc.sh — 파일로 캡처한 검사기의 **rc 를 「판정 불가」로 옮긴다**. **여기가 정본이다.**
#
# 🔴 왜 필요한가 (2026-08-02, 룬드 `#140` 리뷰 ②):
#   `python3 … <<'PY' > "$tmp"` + `viol="$(cat "$tmp")"` 형태는 **rc 를 아무도 안 본다**.
#   파이썬이 죽으면 tmp 가 비고 `viol=""` 가 되어 **«위반 0건» 초록**이 난다 —
#   빈 출력의 두 뜻(«위반 없음» vs «못 쟀다»)이 접히는 자리다.
#
#   🔑 **파일 경유가 이 자리를 열어줬다.** `viol=$( … << )` 일 땐 rc 가 대입에 묻혀 **잴 수가 없었다**.
#     ⇒ `#140` 의 형태 제거는 이식성만 고친 게 아니라 **관측 가능성을 늘렸다**. 이 파일이 그 값을 쓴다.
#
# 사용:
#     python3 - "$X" <<'PYEOF' > "$tmp"
#     …
#     PYEOF
#     rc=$?                                  # 🔴 PYEOF «바로 다음 줄»이어야 한다
#     viol="$(cat "$tmp")"; rm -f "$tmp"
#     if msg="$(hf_verdict "$rc" 이식성)"; then
#         [ -z "$viol" ] && ok "…" || bad "…"
#     else
#         bad "$msg" "rc=0" "«$viol»"
#     fi
#
# 🔸 **이 헬퍼가 못 보는 것**: 파이썬이 rc=0 으로 끝나면서 **틀린 답**을 내는 경우는 못 잡는다.
#   그건 변이시험의 몫이다. 여기가 잠그는 건 «죽었는데 조용한 것» 하나뿐이다.

# hf_verdict <rc> [라벨] — rc=0 이면 조용히 0. 그 밖이면 사유 한 줄을 내고 1.
# 🔑 rc 를 «안 넘기면» 통과가 아니라 실패로 친다 — 배선을 빠뜨린 자리가 조용하면,
#   이 헬퍼를 붙였다는 사실 자체가 초록의 근거가 되어버린다.
hf_verdict() {
    case "${1:-}" in
        0) return 0 ;;
        ''|*[!0-9]*)
            printf '⛔ 판정 불가 — %s 검사기의 rc 를 «안 넘겼다»(배선 누락)\n' "${2:-검사}"
            return 1 ;;
    esac
    printf '⛔ 판정 불가 — %s 검사기가 rc=%s 로 죽었다 (빈 출력은 «위반 0건»이 아니다)\n' "${2:-검사}" "$1"
    return 1
}
